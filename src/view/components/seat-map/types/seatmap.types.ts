// universal-seatmap.types.ts
// Универсальный формат данных карты мест (версия 1.0)
// Теперь содержит массив рейсов (направлений)

// ---------------------------------------------------------------------
// Корневая структура
// ---------------------------------------------------------------------

export interface UniversalSeatMap {
  /** Версия формата (фиксированная) */
  formatVersion: '1.0'
  /** Опциональный идентификатор клиента (для служебных целей) */
  clientId?: string
  /** Список всех рейсов (направлений) из исходных данных */
  flights: FlightWithDirection[]
}

// ---------------------------------------------------------------------
// Рейс с направлением
// ---------------------------------------------------------------------

export interface FlightWithDirection {
  /** Направление: TO – туда, BACK – обратно */
  direction: Direction
  /** Данные рейса */
  flight: Flight
}

// ---------------------------------------------------------------------
// Направление
// ---------------------------------------------------------------------

export type Direction = 'TO' | 'BACK'

// ---------------------------------------------------------------------
// Рейс
// ---------------------------------------------------------------------

export interface Flight {
  /** Сквозной номер рейса */
  flightNumber?: string
  /** Код аэропорта вылета (IATA) */
  departureAirport?: string
  /** Код аэропорта прилёта (IATA) */
  arrivalAirport?: string
  /** Дата и время вылета (ISO 8601) */
  departureDateTime?: string
  /** Дата и время прилёта (ISO 8601) */
  arrivalDateTime?: string
  /** Список сегментов (этапов перелёта) */
  segments: Segment[]
}

// ---------------------------------------------------------------------
// Сегмент
// ---------------------------------------------------------------------

export interface Segment {
  /** Уникальный идентификатор сегмента в рамках рейса */
  segmentId: string
  /** Номер рейса на данном сегменте (может отличаться от сквозного) */
  flightNumber?: string
  /** Код аэропорта вылета сегмента */
  departureAirport?: string
  /** Код аэропорта прилёта сегмента */
  arrivalAirport?: string
  /** Дата и время вылета сегмента */
  departureDateTime?: string
  /** Дата и время прилёта сегмента */
  arrivalDateTime?: string
  /** Код типа воздушного судна (например, SU9) */
  aircraftCode?: string
  /** Название типа ВС (например, Airbus A320) */
  aircraftType?: string
  /** Список палуб на данном сегменте */
  decks: Deck[]
}

// ---------------------------------------------------------------------
// Палуба
// ---------------------------------------------------------------------

export interface Deck {
  /** Идентификатор палубы (уникален в рамках сегмента) */
  deckId: string
  /** Отображаемое название палубы (например, "Maindeck") */
  deckName?: string
  /** Список салонов (кабин) на палубе */
  cabins: Cabin[]
}

// ---------------------------------------------------------------------
// Салон (кабина)
// ---------------------------------------------------------------------

export interface Cabin {
  /** Идентификатор салона (уникален в рамках палубы) */
  cabinId: string
  /** Класс обслуживания (например, "Economy", "Business") */
  cabinClass?: string
  /** Код класса (например, "Y", "C") */
  serviceClass?: string
  /** Ширина салона в условных единицах (для отображения) */
  width?: number
  /** Высота салона (для отображения) */
  height?: number
  /** Список рядов в данном салоне */
  rows: Row[]
  /**
   * Основные двери/входы салона (не аварийные выходы у крыла — те привязаны
   * к конкретному ряду, см. SeatFeature 'Exit' и производный от него Row.rowProps).
   * Дверь — конструктивный элемент фюзеляжа, не привязанный к ряду с местами.
   */
  doors?: Door[]
}

// ---------------------------------------------------------------------
// Дверь салона
// ---------------------------------------------------------------------

export interface Door {
  /** Положение двери вдоль фюзеляжа относительно этого салона */
  position: 'front' | 'rear' | 'mid'
  /** Сторона фюзеляжа */
  side: 'left' | 'right' | 'both'
}

// ---------------------------------------------------------------------
// Ряд
// ---------------------------------------------------------------------

export interface Row {
  /** Номер ряда. Обычно целое число, но может быть дробным для служебных зон (например, 0.5) */
  rowNumber: number
  /**
   * Свойства ряда (например, ["Bulkhead", "NoRow"], ["Overwing"], ["Exit"]).
   * "Overwing"/"Exit" вычисляются драйвером на этапе конвертации по наличию
   * у мест в ряду соответствующего SeatFeature — см. drivers/rowFeatures.ts.
   */
  rowProps?: string[]
  /** Список ячеек ряда в порядке слева направо */
  cells: Cell[]
}

// ---------------------------------------------------------------------
// Ячейка (объединение типов)
// ---------------------------------------------------------------------

export type Cell = SeatCell | EmptyCell | AisleCell

// ---------------------------------------------------------------------
// Типы ячеек
// ---------------------------------------------------------------------

/** Пассажирское кресло */
export interface SeatCell {
  kind: 'seat'
  /** Буква места (A, C, D, E, F и т.д.) */
  letter: string
  /** Доступность места */
  availability: SeatAvailability
  /** Особенности места (массив строк) */
  features: SeatFeature[]
  /** Цена за выбор места (если применимо) */
  price?: number
  /** Валюта цены (например, RUB, USD) */
  currency?: string
  /** Идентификатор услуги, к которой привязано место */
  serviceId?: string
  /** Ограничения (например, ["WithInfant", "A"]) */
  restrictions?: string[]
  /** Дополнительный текст для отображения (например, номер места) */
  freeText?: string
  /** Прочие свойства (запасной массив) */
  props?: string[]
}

/** Пустое место (отсутствие кресла) */
export interface EmptyCell {
  kind: 'empty'
  /** Свойства пустой ячейки (например, ["Bulkhead"]) */
  props?: string[]
}

/** Проход между группами кресел */
export interface AisleCell {
  kind: 'aisle'
  /** Ширина прохода (опционально) */
  width?: number
  /** Свойства прохода */
  props?: string[]
}

// ---------------------------------------------------------------------
// Вспомогательные типы
// ---------------------------------------------------------------------

/** Доступность места */
export type SeatAvailability = 'available' | 'occupied' | 'blocked' | 'unavailable'

/** Основные особенности мест (могут быть расширены) */
export type SeatFeature =
  | 'Window'
  | 'Aisle'
  | 'ExtraLegRoom'
  | 'Overwing'
  | 'LimitedRecline'
  | 'WithInfant'
  | 'Bulkhead'
  | 'NoRow'
  /** Место у аварийного выхода. Как и 'Overwing', драйвер дополнительно
   * поднимает этот признак на уровень ряда (Row.rowProps) — см. drivers/rowFeatures.ts */
  | 'Exit'
  | string // для кастомных значений
